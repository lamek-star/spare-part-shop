import { Database } from "../db/connection";
import { migrate } from "../db/migrate";
import { migrations } from "../db/migrations";
import { permissions, rolePermissions } from "../domain/permissions";
import { roles } from "../domain/types";
import { buildRouter } from "../http/routes";

/**
 * Reference tables generated from the code itself, so the documentation
 * cannot drift from what the application actually does. A test regenerates
 * these and fails when the committed files are stale.
 */
export function permissionsMatrix(): string {
  const head = `| Permission | ${roles.join(" | ")} |\n| --- | ${roles.map(() => ":---:").join(" | ")} |`;
  const rows = permissions.map(
    (p) =>
      `| \`${p}\` | ${roles.map((r) => (rolePermissions[r].has(p) ? "yes" : "")).join(" | ")} |`,
  );
  return `<!-- Generated by \`npm run docs:generate\`. Do not edit by hand. -->\n\n# Role and permission matrix\n\n${head}\n${rows.join("\n")}\n`;
}

export function apiRoutes(): string {
  const routes = buildRouter().entries();
  const lines = routes.map(
    (r) =>
      `| ${r.method} | \`/api/v1${r.path}\` | ${r.options.public ? "public" : (r.options.permission ?? "any signed-in user")} | ${r.options.maxBytes ? `${Math.round(r.options.maxBytes / 1024 / 1024)} MB upload` : ""} |`,
  );
  return `<!-- Generated by \`npm run docs:generate\`. Do not edit by hand. -->\n\n# HTTP API routes (${routes.length})\n\nEvery route except the public ones requires a session cookie; every state-changing call also requires the \`X-CSRF-Token\` header and a same-origin \`Origin\`.\n\n| Method | Path | Permission | Notes |\n| --- | --- | --- | --- |\n${lines.join("\n")}\n`;
}

export async function schemaReference(): Promise<string> {
  const db = Database.open(":memory:");
  try {
    await migrate(db);
    // SQLite catalogue introspection: the synchronous handle is enough and
    // nothing else is using this throwaway in-memory database.
    const h = db.handle;
    {
      const tables = h.all<{ name: string; sql: string }>(
        "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'catalogue_search_%' ORDER BY name",
      );
      const out = tables.map((t) => {
        const cols = h.all<{
          name: string;
          type: string;
          notnull: number;
          pk: number;
        }>(`PRAGMA table_info(${t.name})`);
        const fks = h.all<{ from: string; table: string }>(
          `PRAGMA foreign_key_list(${t.name})`,
        );
        const idx = h
          .all<{ name: string; unique: number }>(`PRAGMA index_list(${t.name})`)
          .filter((i) => !i.name.startsWith("sqlite_autoindex"));
        return `### ${t.name}\n\n${cols.map((c) => `- \`${c.name}\` ${c.type || ""}${c.pk ? " (primary key)" : ""}${c.notnull && !c.pk ? " not null" : ""}${fks.find((f) => f.from === c.name) ? ` -> ${fks.find((f) => f.from === c.name)!.table}` : ""}`).join("\n")}${idx.length ? `\n\nIndexes: ${idx.map((i) => `${i.name}${i.unique ? " (unique)" : ""}`).join(", ")}` : ""}\n`;
      });
      return `<!-- Generated by \`npm run docs:generate\`. Do not edit by hand. -->\n\n# Database schema (migrations ${migrations.map((m) => m.version).join(", ")})\n\n${out.join("\n")}`;
    }
  } finally {
    await db.close();
  }
}
