export function mergeNengunCatalogue(state: State): State {
  const s = structuredClone(state);
  let added = 0;
  const partId = (n: string) => `nengun-mitsubishi-${n}`;
  const numId = (n: string) => `nengun-oe-${n}`;
  for (const [
    number,
    diagram,
    name,
    price,
    availability,
    quantity,
    range,
    specification,
    replacement,
  ] of rows) {
    if (s.parts.some((p) => p.id === partId(number))) continue;
    const p: Part = {
      id: partId(number),
      sku: `MIT-${number}`,
      name,
      brand: "Mitsubishi",
      manufacturer: "Mitsubishi",
      category: "Lighting",
      description: `Nengun supplier listing for ${number}. Headlamp 1 catalogue, Lancer Evolution IX / CT9A / 2003 / SJGFZ / 4G63. Shared assembly diagram; not an individual item photograph.`,
      cost: 0,
      price: 0,
      pricingPending: true,
      currency: "AED",
      unit: "Each",
      weight: 0,
      origin: "Not supplied",
      reorder: 0,
      minimum: 0,
      status: ["Discontinued", "Replaced"].includes(availability)
        ? "Inactive"
        : "Active",
      images: ["/catalogue/mitsubishi-headlamp.png"],
      notes: `Supplier-listed data, not independently manufacturer-verified. Stock and business prices have not been supplied. Weight is unknown. ${replacement ? `Source replacement: ${replacement}. ` : ""}${number === "8301A619" ? "Product page states usually ships 14 days after payment. " : ""}Applicability dates are preserved as supplied; confirm vehicle/VIN before use.`,
      catalogueSource: {
        provider: "Nengun Performance",
        url: number === "8301A619" ? sourceUrl : diagramUrl,
        diagramUrl,
        diagramCode: diagram,
        observedAt,
        priceJpy: price,
        availability,
        quantityRequired: quantity,
        applicability: ranges[range],
        specification,
      },
    };
    s.parts.push(p);
    added++;
    const n: PartNumber = {
      id: numId(number),
      partId: p.id,
      display: number,
      normalized: normalizeNumber(number),
      type: "OEM_OE",
      brand: "Mitsubishi",
      source: `Nengun Performance · ${observedAt}`,
      market: "Source catalogue: Japan; vehicle market not confirmed",
      active: availability !== "Replaced",
      primary: true,
      notes: p.notes,
      verification: "Supplier listed",
      ...(replacement ? { supersededBy: numId(replacement) } : {}),
    };
    s.numbers.push(
      n,
      {
        ...n,
        id: `nengun-diagram-${number}`,
        display: diagram,
        normalized: diagram,
        type: "CATALOGUE",
        primary: false,
        supersededBy: undefined,
        notes: "Diagram position code, not an orderable OEM number.",
      },
      {
        ...n,
        id: `nengun-sku-${number}`,
        display: p.sku,
        normalized: normalizeNumber(p.sku),
        type: "INTERNAL_SKU",
        supersededBy: undefined,
        notes: "Internal inventory identifier.",
      },
    );
  }
  for (const [number, , , , , , , , replacement] of rows) {
    if (replacement && !s.numbers.some((n) => n.id === numId(replacement)))
      s.numbers.push({
        id: numId(replacement),
        partId: partId(number),
        display: replacement,
        normalized: normalizeNumber(replacement),
        type: "REPLACEMENT",
        brand: "Mitsubishi",
        source: `Nengun Performance · ${observedAt}`,
        market: "Not confirmed",
        active: true,
        primary: false,
        notes: `Listed replacement for ${number}; separate specifications and price not supplied in this table.`,
        verification: "Supplier listed",
      });
  }
  const fitments: [string, string, string, number[], number[]][] = [
    [
      "IX",
      "CT9A",
      "SJGFZ",
      [2000, 2001, 2003, 2004, 2005],
      [177008, 177009, 177011, 177012, 177013],
    ],
    [
      "VII",
      "CT9A",
      "SYGFZ",
      [2000, 2001, 2002, 2004, 2005],
      [177028, 177029, 177030, 177032, 177033],
    ],
    [
      "VIII",
      "CT9A",
      "SJDFZ",
      [2000, 2001, 2002, 2003, 2004],
      [176998, 176999, 177000, 177001, 177002],
    ],
    [
      "Wagon",
      "CT9W",
      "LJGFZ",
      [2000, 2002, 2003, 2005, 2006],
      [141465, 141467, 141468, 141470, 141471],
    ],
  ];
  for (const [model, chassis, grade, years, ids] of fitments)
    years.forEach((year, i) => {
      const id = `nengun-vehicle-${ids[i]}`;
      if (!s.vehicles.some((v) => v.id === id))
        s.vehicles.push({
          id,
          make: "Mitsubishi",
          model: `Lancer Evolution ${model}`,
          variant: `${chassis} / ${grade}`,
          from: year,
          to: year,
          engine: "Not supplied",
          engineCode: "4G63",
          transmission: "Not supplied",
        });
      const linkId = `nengun-fit-8301A619-${ids[i]}`;
      if (!s.compatibility.some((c) => c.id === linkId))
        s.compatibility.push({
          id: linkId,
          partId: partId("8301A619"),
          vehicleId: id,
          source: sourceUrl,
          notes:
            "Supplier catalogue association only. Source vehicle/year labels are preserved verbatim, not independently verified; confirm VIN. The source also mentions additional vehicles without listing their details.",
        });
    });
  for (const [number, , , , , , range] of rows) {
    const id = `nengun-table-fit-${number}`;
    if (number !== "8301A619" && !s.compatibility.some((c) => c.id === id))
      s.compatibility.push({
        id,
        partId: partId(number),
        vehicleId: "nengun-vehicle-177011",
        source: diagramUrl,
        notes: `Headlamp table context only, not guaranteed fitment. Applicability as published: ${ranges[range] || "Not supplied"}.`,
      });
  }
  if (added)
    s.audit.unshift({
      id: "import-nengun-headlamp-2026-09-10",
      date: "2026-09-10T00:00:00.000Z",
      action: "Supplier catalogue imported",
      detail: `${added} headlamp table records imported from Nengun; shared user-provided diagram; no stock movements or AED prices created.`,
      actor: "Catalogue import",
    });
  return s;
}
